"""Build the library views as markdown.

Sections: deliverable status (rolled up from citations, current version only),
qualitative findings, lanes, contradicting evidence, citations with sync status,
staleness (and blanks listed so they cannot hide), the punch list, the ship guard,
tensions, and integrity checks including vocabulary yields.
"""

from __future__ import annotations

import datetime as dt
from collections import defaultdict
from pathlib import Path

from gsps.cascade.derived import estimates_with_moved_inputs
from gsps.library import Library
from gsps.rules.confidence import confidence
from gsps.rules.freshness import is_stale, sync_status, worst_status
from gsps.rules.integrity import run_integrity_checks
from gsps.store.versioned import next_version_path, write_new
from gsps.vocab.values import AnchorType, AuthorityTier, Confidence, Grade, Stance, SyncStatus


def _rel(lib: Library, p: Path | None) -> str:
    if p is None:
        return "-"
    try:
        return p.relative_to(lib.root).as_posix()
    except ValueError:
        return p.as_posix()


def build_views(lib: Library, as_of: dt.date, *, simulated: bool = False) -> str:
    anchors = lib.anchors
    by_id = lib.anchors_by_id
    out: list[str] = []
    p = out.append

    inputs = ", ".join(f"`{_rel(lib, v)}`" for v in lib.sources.values())
    p(f"# VIEWS as of {as_of}{' (SIMULATED DATE)' if simulated else ''}\n")
    p(f"Generated by gsps. Do not edit. Inputs: {inputs}.\n")

    p("## 0. Deliverables: status rolled up from current-version citations")
    p("| Deliverable | Name | Stage | Rows | In sync | At risk | Behind | Status |")
    p("|---|---|---|---|---|---|---|---|")
    for d in lib.deliverables:
        rs = [
            sync_status(c, by_id, as_of)
            for c in lib.citations
            if c.deliverable_id == d.deliverable_id and c.deliverable_version == d.current_version
        ]
        worst = worst_status(rs)
        stage = d.status_stage + (f" (shipped {d.shipped_date}, frozen)" if d.shipped_date else "")
        p(
            f"| {d.deliverable_id} | {d.name} | {stage} | {len(rs)} | "
            f"{rs.count(SyncStatus.IN_SYNC)} | {rs.count(SyncStatus.AT_RISK)} | "
            f"{rs.count(SyncStatus.BEHIND)} | **{worst.value if worst else 'no citations'}** |"
        )

    p("\n## 1. Qualitative (anchor_type = finding)")
    p("| Anchor | Institution | Claim | Grade | Tier | Stance | Counterweight |")
    p("|---|---|---|---|---|---|---|")
    for a in anchors:
        if a.anchor_type == AnchorType.FINDING:
            f = lib.findings.get(a.anchor_id)
            p(
                f"| {a.anchor_id} | {f.institution if f else ''} | "
                f"{f.claim if f else '(no FINDINGS row)'} | {a.grade} | {a.authority_tier} | "
                f"{(f.stance + ' on ' + f.stance_on) if f else ''} | "
                f"{(f.counterweight or f.counterweight_status) if f else ''} |"
            )

    p("\n## 2. By lane\n| Lane | Anchors | Types |\n|---|---|---|")
    lanes: dict[str, list[str]] = defaultdict(list)
    types: dict[str, set[str]] = defaultdict(set)
    for a in anchors:
        lanes[a.lane].append(a.anchor_id)
        types[a.lane].add(a.anchor_type)
    for lane, ids in lanes.items():
        p(f"| {lane} | {', '.join(ids)} | {', '.join(sorted(types[lane]))} |")

    p("\n## 3. Contradicts our thesis (check before every ship)")
    p("| Anchor | Contradicts | Evidence |\n|---|---|---|")
    hits = [f for f in lib.findings.values() if f.stance == Stance.CONTRADICTS]
    for f in hits:
        p(f"| {f.anchor_id} | {f.stance_on} | {f.verbatim[:160]} |")
    if not hits:
        p("| - | none | - |")

    p("\n## 4. Citations with sync status (computed on value_version)")
    p("| Deliverable | Location | Token | Anchor | Cited | Current | Sync |")
    p("|---|---|---|---|---|---|---|")
    for c in lib.citations:
        cur = by_id.get(c.anchor_id)
        p(
            f"| {c.deliverable_id} | {c.location} | {c.token} | {c.anchor_id} | "
            f"{c.anchor_value_version} | {cur.value_version if cur else 'MISSING'} | "
            f"{sync_status(c, by_id, as_of).value} |"
        )

    p("\n## 5. Staleness (as-of date on/after next_release, not re-walked since)")
    p("| Anchor | last_walked | next_release | basis | label | State |")
    p("|---|---|---|---|---|---|")
    for a in anchors:
        if a.next_release:
            state = "STALE" if is_stale(a, as_of) else "fresh"
            p(
                f"| {a.anchor_id} | {a.last_walked} | {a.next_release} | {a.refresh_basis} | "
                f"{a.next_release_label} | {state} |"
            )
    p("\n**No refresh date (never auto-stale; listed so blanks cannot hide):**\n")
    p("| Anchor | basis | label |\n|---|---|---|")
    for a in anchors:
        if not a.next_release:
            p(f"| {a.anchor_id} | {a.refresh_basis} | {a.next_release_label} |")

    p("\n## 6. Punch list (walk to-dos and human-in-the-loop)\n| Anchor | Item |\n|---|---|")
    for a in anchors:
        note = a.ceiling_note
        if a.ceiling in {"effort", "access"} or "walk-TODO" in note or "HITL" in note:
            p(f"| {a.anchor_id} | [{a.ceiling}] {note} |")
        if a.authority_tier == AuthorityTier.THIRD_PARTY_UNKNOWN:
            p(
                f"| {a.anchor_id} | classify the source kind "
                "(3rd-party-unknown is a holding label) |"
            )
    for est, moved in estimates_with_moved_inputs(anchors).items():
        p(f"| {est} | recompute: inputs moved since it was computed ({', '.join(moved)}) |")
    for f in lib.findings.values():
        if "pending" in f.counterweight_status:
            p(f"| {f.anchor_id} | counterweight {f.counterweight_status} |")

    p("\n## 7. Ship guard\n| Anchor | H/M/L | Rule |\n|---|---|---|")
    for a in anchors:
        conf = confidence(a)
        if conf in {Confidence.NOT_SHIPPABLE, Confidence.NO_VALUE}:
            p(f"| {a.anchor_id} | {conf.value} | do not cite |")
        elif a.grade == Grade.HYPOTHESIS:
            p(f"| {a.anchor_id} | {conf.value} | ship only labeled 'estimate', math available |")
        elif a.authority_tier in {
            AuthorityTier.COMPANY_RESEARCH,
            AuthorityTier.COMMERCIAL_PUBLISHER,
        }:
            p(f"| {a.anchor_id} | {conf.value} | name the source in the copy; interest flag |")

    p("\n## 8. Tensions and reconciliation flags")
    p("| Flag | Token | Anchors | Type | Status |\n|---|---|---|---|---|")
    for t in sorted(lib.tensions, key=lambda t: (t.token == "", t.flag_id)):
        p(f"| {t.flag_id} | {t.token or '-'} | {t.anchors} | {t.flag_type} | {t.status} |")

    p("\n## 9. Integrity and vocabulary (runs every time)\n| Check | Result |\n|---|---|")
    for r in run_integrity_checks(
        anchors, lib.citations, lib.deliverables, lib.findings, lib.registry
    ):
        p(f"| {r.name} | {'OK' if r.ok else 'FLAG: ' + ', '.join(r.offenders)} |")

    return "\n".join(out) + "\n"


def write_views(lib: Library, as_of: dt.date | None = None) -> Path:
    """Write the views as a new dated version under ``<root>/VIEWS/``."""
    day = as_of or dt.date.today()
    target = next_version_path(lib.root / "VIEWS", "VIEWS", "md", on=dt.date.today())
    target.parent.mkdir(parents=True, exist_ok=True)
    return write_new(target, build_views(lib, day, simulated=as_of is not None))
